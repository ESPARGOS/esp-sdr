#!/usr/bin/env python3
"""Render the ESPARGOS wordmark as an LVGL alpha-only (A8) image for the Korvo UI.

The logo is a single colour, so only coverage is stored; the UI picks the
colour with LVGL's image recolor style. Needs rsvg-convert and Pillow:

    tools/korvo_logo.py ../esp-web-sdr/espargos-logo.svg main/targets/esp32s31/korvo/logo.c --height 34
"""
import argparse
import io
import subprocess

from PIL import Image


def render(svg, height):
    png = subprocess.run(['rsvg-convert', '-w', '1600', '-b', 'none', svg], check=True, capture_output=True).stdout
    image = Image.open(io.BytesIO(png)).convert('RGBA')
    alpha = image.getchannel('A')
    box = alpha.getbbox()
    alpha = alpha.crop(box)
    width = round(alpha.width * height / alpha.height)
    return alpha.resize((width, height), Image.LANCZOS)


def emit(alpha, source, out):
    data = alpha.tobytes()
    lines = [f'/* Generated by tools/korvo_logo.py from {source}: ESPARGOS wordmark, {alpha.width}x{alpha.height} A8. */',
             '#include "lvgl.h"', '', 'static const uint8_t logo_map[] = {']
    for at in range(0, len(data), 24):
        lines.append('    ' + ''.join(f'0x{b:02x},' for b in data[at:at + 24]))
    lines += ['};', '', 'const lv_image_dsc_t espargos_logo = {',
              f'    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {alpha.width}, .h = {alpha.height}, .stride = {alpha.width}}},',
              '    .data_size = sizeof(logo_map),', '    .data = logo_map,', '};', '']
    with open(out, 'w') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('svg')
    parser.add_argument('output')
    parser.add_argument('--height', type=int, default=34)
    args = parser.parse_args()
    emit(render(args.svg, args.height), 'esp-web-sdr/espargos-logo.svg', args.output)
    print(args.output)
